    ESTIMATED_DURATION_MINUTES NUMBER(5) CONSTRAINT CK_ROUTE_DURATION CHECK (ESTIMATED_DURATION_MINUTES IS NULL OR ESTIMATED_DURATION_MINUTES > 0),
    IS_ACTIVE                  CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT CK_ROUTE_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N')),
    UPDATED_AT                 TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_ROUTE_FARE UNIQUE (PICKUP_LOCATION, DESTINATION),
    CONSTRAINT CK_ROUTE_LOCATIONS CHECK (PICKUP_LOCATION <> DESTINATION)
);

