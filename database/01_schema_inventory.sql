-- 1. APP_USER (Supertype)
-- Base account record for students, faculty, and administrators.
CREATE TABLE APP_USER (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME       VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(254) NOT NULL CONSTRAINT UQ_APP_USER_EMAIL UNIQUE,
    PASSWORD_HASH   VARCHAR2(255) NOT NULL,
    USER_ROLE       VARCHAR2(20)  NOT NULL CONSTRAINT CK_APP_USER_ROLE CHECK (USER_ROLE IN ('STUDENT', 'FACULTY', 'ADMIN')),
    ACCOUNT_STATUS  VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL CONSTRAINT CK_APP_USER_STATUS CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CREATED_AT      TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. STUDENT_PROFILE (Subtype)
CREATE TABLE STUDENT_PROFILE (
    USER_ID         NUMBER PRIMARY KEY CONSTRAINT FK_STUDENT_PROFILE_USER REFERENCES APP_USER(USER_ID),
    REGISTRATION_NO VARCHAR2(30) NOT NULL CONSTRAINT UQ_STUDENT_REGISTRATION UNIQUE,
    PROGRAMME       VARCHAR2(100),
    STUDY_YEAR      NUMBER(1) CONSTRAINT CK_STUDENT_STUDY_YEAR CHECK (STUDY_YEAR BETWEEN 1 AND 6)
);

-- 3. FACULTY_PROFILE (Subtype)
CREATE TABLE FACULTY_PROFILE (
    USER_ID         NUMBER PRIMARY KEY CONSTRAINT FK_FACULTY_PROFILE_USER REFERENCES APP_USER(USER_ID),
    EMPLOYEE_ID     VARCHAR2(30) NOT NULL CONSTRAINT UQ_FACULTY_EMPLOYEE UNIQUE,
    STAFF_CATEGORY  VARCHAR2(20) NOT NULL CONSTRAINT CK_FACULTY_CATEGORY CHECK (STAFF_CATEGORY IN ('TEACHING', 'NON_TEACHING')),
    DEPARTMENT      VARCHAR2(100)
);

-- 4. RIDE_REQUEST
CREATE TABLE RIDE_REQUEST (
    REQUEST_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUESTER_ID     NUMBER NOT NULL CONSTRAINT FK_REQUEST_REQUESTER REFERENCES APP_USER(USER_ID),
    REQUEST_TYPE     VARCHAR2(30) NOT NULL CONSTRAINT CK_REQUEST_TYPE CHECK (REQUEST_TYPE IN ('LOOKING_FOR_COMPANIONS', 'VEHICLE_ARRANGED')),
    PICKUP_LOCATION  VARCHAR2(200) NOT NULL,
    DESTINATION      VARCHAR2(200) NOT NULL,
    DEPARTURE_TIME   TIMESTAMP(6) NOT NULL,
    REQUEST_STATUS   VARCHAR2(20) DEFAULT 'OPEN' NOT NULL CONSTRAINT CK_REQUEST_STATUS CHECK (REQUEST_STATUS IN ('OPEN', 'MATCHED', 'CANCELLED', 'CLOSED')),
    CREATED_AT       TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_REQUEST_LOCATIONS CHECK (PICKUP_LOCATION <> DESTINATION)
);

-- 5. RIDE_GROUP
CREATE TABLE RIDE_GROUP (
    GROUP_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REQUEST_ID            NUMBER NOT NULL CONSTRAINT FK_GROUP_REQUEST REFERENCES RIDE_REQUEST(REQUEST_ID),
    COORDINATOR_ID        NUMBER NOT NULL CONSTRAINT FK_GROUP_COORDINATOR REFERENCES APP_USER(USER_ID),
    DEPARTURE_TIME        TIMESTAMP(6) NOT NULL,
    GROUP_STATUS          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL CONSTRAINT CK_GROUP_STATUS CHECK (GROUP_STATUS IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED', 'EXPIRED', 'CLOSED')),
    ESTIMATED_FARE        NUMBER(10,2) CONSTRAINT CK_GROUP_ESTIMATED_FARE CHECK (ESTIMATED_FARE IS NULL OR ESTIMATED_FARE >= 0),
    ACTUAL_FARE           NUMBER(10,2) CONSTRAINT CK_GROUP_ACTUAL_FARE CHECK (ACTUAL_FARE IS NULL OR ACTUAL_FARE >= 0),
    CREATED_AT            TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONFIRMATION_DEADLINE TIMESTAMP(6)
);

-- 6. RIDE_GROUP_MEMBER
CREATE TABLE RIDE_GROUP_MEMBER (
    MEMBERSHIP_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GROUP_ID          NUMBER NOT NULL CONSTRAINT FK_MEMBER_GROUP REFERENCES RIDE_GROUP(GROUP_ID),
    USER_ID           NUMBER NOT NULL CONSTRAINT FK_MEMBER_USER REFERENCES APP_USER(USER_ID),
    MEMBER_ROLE       VARCHAR2(20) DEFAULT 'PASSENGER' NOT NULL CONSTRAINT CK_MEMBER_ROLE CHECK (MEMBER_ROLE IN ('COORDINATOR', 'PASSENGER')),
    MEMBERSHIP_STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL CONSTRAINT CK_MEMBERSHIP_STATUS CHECK (MEMBERSHIP_STATUS IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'LEFT')),
    JOINED_AT         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

-- Function-based Unique Index: At most one active membership per user per group
CREATE UNIQUE INDEX UQ_ACTIVE_GROUP_MEMBER ON RIDE_GROUP_MEMBER (
    CASE MEMBERSHIP_STATUS WHEN 'PENDING' THEN GROUP_ID WHEN 'CONFIRMED' THEN GROUP_ID END,
    CASE MEMBERSHIP_STATUS WHEN 'PENDING' THEN USER_ID WHEN 'CONFIRMED' THEN USER_ID END
);

-- 7. ROUTE_FARE
