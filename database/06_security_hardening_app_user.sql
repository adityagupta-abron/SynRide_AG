-- 9. Enable Dedicated Least-Privilege Proxy Access
ALTER USER SYNRIDE GRANT CONNECT THROUGH SYNRIDE_APP;

-- 10. Revoke SYSTEM Proxy Access (Hardening)
BEGIN
    EXECUTE IMMEDIATE 'ALTER USER SYNRIDE REVOKE CONNECT THROUGH SYSTEM';
EXCEPTION
    WHEN OTHERS THEN
        NULL; -- Ignore if already revoked
END;
/

COMMIT;
