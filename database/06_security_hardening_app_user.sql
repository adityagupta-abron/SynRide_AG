GRANT SELECT, INSERT, UPDATE, DELETE ON SYNRIDE.EMAIL_DELIVERY_LOG TO RL_SYNRIDE_APP;

-- 5. Grant SELECT Privileges on all 5 Views to Application Role
GRANT SELECT ON SYNRIDE.V_USER_PROFILES TO RL_SYNRIDE_APP;
GRANT SELECT ON SYNRIDE.V_ACTIVE_RIDE_GROUPS TO RL_SYNRIDE_APP;
GRANT SELECT ON SYNRIDE.V_RIDE_GROUP_MEMBERS_DETAIL TO RL_SYNRIDE_APP;
GRANT SELECT ON SYNRIDE.V_USER_RATINGS_SUMMARY TO RL_SYNRIDE_APP;
GRANT SELECT ON SYNRIDE.V_ADMIN_REVIEW_QUEUE TO RL_SYNRIDE_APP;

-- 6. Grant EXECUTE Privileges on all 8 Stored Procedures to Application Role
GRANT EXECUTE ON SYNRIDE.JOIN_RIDE_GROUP TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.SET_CONFIRMATION_DEADLINE TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.RECORD_RIDE_CONFIRMATION TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.DECLINE_RIDE_CONFIRMATION TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.CONFIRM_RIDE_GROUP TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.EXPIRE_UNCONFIRMED_GROUP TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.REPLACE_COORDINATOR TO RL_SYNRIDE_APP;
GRANT EXECUTE ON SYNRIDE.CALCULATE_AND_ALLOCATE_FARE TO RL_SYNRIDE_APP;

-- 7. Assign Role to Application User and Set as Default
GRANT RL_SYNRIDE_APP TO SYNRIDE_APP;
ALTER USER SYNRIDE_APP DEFAULT ROLE RL_SYNRIDE_APP;

