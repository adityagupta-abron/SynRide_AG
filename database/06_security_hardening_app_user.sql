-- ============================================================================
-- SCRIPT 06: Security Hardening - Dedicated Application Account & Least Privilege
-- Database: Oracle AI Database 26ai Free (FREEPDB1)
-- Description: Replaces SYSTEM proxy authentication with a dedicated application
--              account (SYNRIDE_APP) granting ONLY the required DML privileges on
--              the SYNRIDE schema objects, views, and PL/SQL procedures.
-- ============================================================================

ALTER SESSION SET CONTAINER = FREEPDB1;

-- 1. Create Dedicated Application User (if not already exists)
-- Replace 'YourStrongAppPasswordHere123!' with your local secure secret
DECLARE
    v_user_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_user_count FROM dba_users WHERE username = 'SYNRIDE_APP';
    IF v_user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER SYNRIDE_APP IDENTIFIED BY "YourStrongAppPasswordHere123!"';
    END IF;
END;
/

-- 2. Create Application Role for Least-Privilege Management
DECLARE
    v_role_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_role_count FROM dba_roles WHERE role = 'RL_SYNRIDE_APP';
    IF v_role_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE ROLE RL_SYNRIDE_APP';
    END IF;
END;
/

-- 3. Grant Session Creation to Application User
GRANT CREATE SESSION TO SYNRIDE_APP;

-- 4. Grant DML Privileges on all 18 Tables to Application Role
GRANT SELECT, INSERT, UPDATE, DELETE ON SYNRIDE.APP_USER TO RL_SYNRIDE_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON SYNRIDE.STUDENT_PROFILE TO RL_SYNRIDE_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON SYNRIDE.FACULTY_PROFILE TO RL_SYNRIDE_APP;
